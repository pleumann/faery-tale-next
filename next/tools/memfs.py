#!/usr/bin/env python3
"""Pack the game data files into free 8K pages of a 2 MB Next and append them to a NEX.

  memfs.py header <FTA-dir> <memfs.h>            allocate, write the C table
  memfs.py pack   <FTA-dir> <in.nex> <out.nex>   allocate the same way, write the NEX

Files are placed byte-wise into runs of consecutive free pages; TILES.DAT and SHAPES.DAT
start on page boundaries (the game uses them in place). The runtime (src/platform/
files.c, MEMFS) reads them with the usual file functions.
"""
import os
import struct
import sys

# pages the program uses at run time in the 2 MB build (see README memory map)
FREE_RUNS = [(2, 2), (6, 4), (12, 2), (16, 2), (38, 18), (63, 10), (79, 1), (90, 134)]
PAGE = 8192
ALIGNED = ("TILES.DAT", "SHAPES.DAT")


def data_files(fta):
    names = sorted(n for n in os.listdir(fta) if not n.startswith("SAVE") and not n.startswith("."))
    big = [n for n in names if n in ALIGNED]
    rest = sorted((n for n in names if n not in ALIGNED),
                  key=lambda n: -os.path.getsize(os.path.join(fta, n)))
    return [n for n in ALIGNED if n in big] + rest


def allocate(fta):
    """-> list of (name, page, offset, size)"""
    runs = [[start, count, 0] for start, count in FREE_RUNS]   # start page, pages, used bytes
    placed = []
    for name in data_files(fta):
        size = os.path.getsize(os.path.join(fta, name))
        for r in runs:
            used = r[2]
            if name in ALIGNED and used % PAGE:
                used += PAGE - used % PAGE
            if used + size <= r[1] * PAGE:
                placed.append((name, r[0] + used // PAGE, used % PAGE, size))
                r[2] = used + size
                break
        else:
            raise SystemExit(f"memfs: no room for {name} ({size} bytes)")
    return placed


def write_header(placed, path):
    with open(path, "w") as h:
        h.write("/* generated by tools/memfs.py - data files packed into RAM pages (2 MB build) */\n")
        h.write("#ifndef MEMFS_H\n#define MEMFS_H\n\n#include <stdint.h>\n\n")
        h.write("struct memfs_file { const char *name; uint8_t page; uint16_t offset; uint32_t size; };\n\n")
        h.write(f"#define MEMFS_COUNT {len(placed)}\n")
        h.write("static const struct memfs_file memfs_files[MEMFS_COUNT] = {\n")
        for name, page, off, size in placed:
            h.write(f'    {{ "FTA/{name}", {page}, {off}, {size}UL }},\n')
        h.write("};\n\n#endif\n")


def pack(fta, placed, nex_in, nex_out):
    d = bytearray(open(nex_in, "rb").read())
    header = d[:512]
    order = [5, 2, 0, 1, 3, 4] + list(range(6, 112))
    present = [b for b in order if header[18 + b]]
    banks = {}
    pos = 512
    for b in present:
        banks[b] = bytearray(d[pos:pos + 16384])
        pos += 16384
    for name, page, off, size in placed:
        data = open(os.path.join(fta, name), "rb").read()
        a = page * PAGE + off
        for i in range(0, size):
            bank, boff = divmod(a + i, 16384)
            if bank not in banks:
                banks[bank] = bytearray(16384)
            banks[bank][boff] = data[i]
    header[8] = 1                                   # needs 1792K (2 MB Next)
    header[9] = len(banks)
    for b in range(112):
        header[18 + b] = 1 if b in banks else 0
    out = bytearray(header)
    for b in order:
        if b in banks:
            out += banks[b]
    with open(nex_out, "wb") as f:
        f.write(out)
    print(f"memfs: {len(placed)} files, NEX {len(out) // 1024} KB, {len(banks)} banks")


def main():
    cmd, fta = sys.argv[1], sys.argv[2]
    placed = allocate(fta)
    if cmd == "header":
        write_header(placed, sys.argv[3])
    else:
        pack(fta, placed, sys.argv[3], sys.argv[4])


if __name__ == "__main__":
    main()
