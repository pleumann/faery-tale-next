#!/usr/bin/env python3
"""Convert the original Amiga game data into Spectrum Next formats.

Usage: convert.py <game-dir> <out-sd-root> <preview-dir> <gen-dir>

All multi-byte values are written little-endian. See next/README.md for the formats.
"""
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import gamedata as gd                      # noqa: E402
from adf import Disk                       # noqa: E402
from amiga import planar_image, first_hunk  # noqa: E402
from iff import read_ilbm                  # noqa: E402
from nextfmt import layer2_320_column_major  # noqa: E402
from png import write_png, write_png_rgb  # noqa: E402

TILE_W, TILE_H = 16, 32
TILE_BYTES = TILE_W * TILE_H               # 512 bytes, 8bpp column-major
BANK_TILES = 64
BANK_BYTES = BANK_TILES * TILE_BYTES       # 32K
MAGENTA = (255, 0, 255)


def rgb4_to_rgb8(c):
    return (((c >> 8) & 15) * 17, ((c >> 4) & 15) * 17, (c & 15) * 17)


PAGE_PAL = [rgb4_to_rgb8(c) for c in gd.PAGECOLORS]


class Out:
    """Collects output files and the #defines for assets.h."""

    def __init__(self, sdroot, prevdir, gendir):
        self.dir = os.path.join(sdroot, "FTA")
        self.prev = prevdir
        self.gen = gendir
        self.defines = []
        for d in (self.dir, self.prev, self.gen):
            os.makedirs(d, exist_ok=True)

    def file(self, name, data):
        with open(os.path.join(self.dir, name), "wb") as f:
            f.write(data)
        print(f"  {name:14s} {len(data):7d} bytes")

    def png(self, name, rows, pal):
        write_png(os.path.join(self.prev, name), rows, list(pal) + [(0, 0, 0)] * (256 - len(pal)))

    def define(self, name, value, comment=""):
        self.defines.append((name, value, comment))

    def write_header(self):
        with open(os.path.join(self.gen, "assets.h"), "w") as h:
            h.write("/* generated by tools/convert.py - do not edit */\n")
            h.write("#ifndef ASSETS_H\n#define ASSETS_H\n\n")
            for name, value, comment in self.defines:
                c = f"  /* {comment} */" if comment else ""
                h.write(f"#define {name:24s} {value}{c}\n")
            h.write("\n#endif\n")


def rgb4_palette_bytes(colors):
    return b"".join(struct.pack("<H", c) for c in colors)


def scale(rows, k):
    """Nearest-neighbour upscale for previews."""
    out = []
    for r in rows:
        wide = bytearray(v for v in r for _ in range(k))
        out += [wide] * k
    return out


# --------------------------------------------------------------------------- tiles

def decode_tile_bank(disk, bank):
    """Return 64 tiles, each a list of 32 rows of 16 indices."""
    raw = disk.blocks(gd.TILE_BANK_FIRST + bank * 40, 40)
    tiles = []
    for t in range(BANK_TILES):
        # plane p of tile t: raw[p*4096 + t*64 .. +64], 2 bytes per row
        planes = [raw[p * 4096 + t * 64:p * 4096 + t * 64 + 64] for p in range(5)]
        rows = planar_image(b"".join(planes), TILE_W, TILE_H, 5, 64)
        tiles.append(rows)
    return tiles


def tile_column_major(rows):
    out = bytearray(TILE_BYTES)
    for y, row in enumerate(rows):
        for x, v in enumerate(row):
            out[x * TILE_H + y] = v
    return out


def convert_tiles(disk, out):
    banks = [decode_tile_bank(disk, b) for b in range(gd.TILE_BANKS)]
    data = bytearray()
    for b, tiles in enumerate(banks):
        for t in tiles:
            data += tile_column_major(t)
        # preview sheet: 16 x 4 tiles
        sheet = []
        for ty in range(4):
            for y in range(TILE_H):
                row = bytearray()
                for tx in range(16):
                    row += tiles[ty * 16 + tx][y]
                sheet.append(row)
        out.png(f"tiles_{b:02d}.png", sheet, PAGE_PAL)
    out.file("TILES.DAT", data)
    out.define("TILE_BANK_FIRST_BLOCK", gd.TILE_BANK_FIRST)
    out.define("TILE_BANK_BYTES", BANK_BYTES)
    out.define("TILE_BYTES", TILE_BYTES)
    return banks


# --------------------------------------------------------------------------- world data

def convert_world(disk, out):
    sectors = disk.blocks(32, 64) + disk.blocks(96, 64)
    maps = b"".join(disk.blocks(b, 8) for b in (160, 168, 176, 184, 192))
    terra = disk.blocks(gd.TERRA_BLOCK, 11)
    out.file("SECTORS.DAT", sectors)
    out.file("MAPS.DAT", maps)
    out.file("TERRA.DAT", terra)
    out.file("SHADOW.DAT", disk.blocks(gd.SHADOW_BLOCK, gd.SHADOW_BLOCKS))
    out.define("SECTORS_OUTDOOR", 0, "offset in SECTORS.DAT")
    out.define("SECTORS_INDOOR", 32768)
    out.define("MAP_BYTES", 4096, "128 x 32 sector numbers per map")
    out.define("TERRA_BYTES", 512, "4 bytes x 128 tiles")
    out.define("SHADOW_MASKS", 192)
    return sectors, maps, terra


def bank_of_block(block):
    return (block - gd.TILE_BANK_FIRST) // 40


def region_tiles(banks, region):
    images = gd.FILE_INDEX[region][0]
    return [banks[bank_of_block(images[n >> 6])][n & 63] for n in range(256)]


def region_terra(terra, region):
    t1, t2 = gd.FILE_INDEX[region][1], gd.FILE_INDEX[region][2]
    return terra[t1 * 512:t1 * 512 + 512] + terra[t2 * 512:t2 * 512 + 512]


def tile_average(tile):
    r = g = b = 0
    for row in tile:
        for v in row:
            c = PAGE_PAL[v]
            r += c[0]
            g += c[1]
            b += c[2]
    n = TILE_W * TILE_H
    return (r // n, g // n, b // n)


def world_previews(banks, sectors, maps, terra, out):
    """world.png: 1 pixel per tile (average colour), world_terrain.png: big_colors."""
    W, H = 128 * 16, 128 * 8
    avg_cache = {}
    rows = [bytearray(W * 3) for _ in range(H)]
    trows = [bytearray(W) for _ in range(H)]
    for band in range(4):
        m = maps[band * 4096:(band + 1) * 4096]
        for half in range(2):
            region = half + 2 * band
            tiles = region_tiles(banks, region)
            rterra = region_terra(terra, region)
            for sy in range(32):
                for sx in range(half * 64, half * 64 + 64):
                    sec = m[sy * 128 + sx]
                    for ty in range(8):
                        for tx in range(16):
                            t = sectors[sec * 128 + ty * 16 + tx]
                            key = (region, t)
                            if key not in avg_cache:
                                avg_cache[key] = bytes(tile_average(tiles[t]))
                            x = sx * 16 + tx
                            y = (band * 32 + sy) * 8 + ty
                            rows[y][x * 3:x * 3 + 3] = avg_cache[key]
                            trows[y][x] = rterra[t * 4 + 3] & 31
    write_png_rgb(os.path.join(out.prev, "world.png"), rows)
    out.png("world_terrain.png", trows, PAGE_PAL)


def render_area(banks, sectors, maps, region, map_base, sector_base, x0, y0, w, h):
    """Render a w x h pixel window at world pixel (x0, y0) of one region."""
    tiles = region_tiles(banks, region)
    rows = []
    for y in range(y0, y0 + h):
        row = bytearray(w)
        ty_world = (y & 0x7FFF) >> 5
        for x in range(x0, x0 + w):
            tx_world = x >> 4
            sec = maps[map_base + ((ty_world >> 3) & 31) * 128 + ((tx_world >> 4) & 127)]
            t = sectors[sector_base + sec * 128 + (ty_world & 7) * 16 + (tx_world & 15)]
            row[x - x0] = tiles[t][y & 31][x & 15]
        rows.append(row)
    return rows


def area_previews(banks, sectors, maps, out):
    sx, sy = gd.SAFE_START
    band = (sy >> 13) & 3
    region = ((sx >> 14) & 1) + 2 * band
    rows = render_area(banks, sectors, maps, region, band * 4096, 0,
                       sx - 512, sy - 256 - band * 8192 + band * 8192, 1024, 512)
    out.png("start.png", rows, PAGE_PAL)
    # indoor overview: top-left 2048 x 1024 pixels of the indoor map (region 8 tiles)
    rows = render_area(banks, sectors, maps, 8, 4 * 4096, 32768, 0, 0, 2048, 1024)
    out.png("indoor.png", rows, PAGE_PAL)


# --------------------------------------------------------------------------- shapes

def convert_shapes(disk, out):
    """Each frame split into 16x16 cells (row-major cells, 256 bytes each, 8bpp).
    SHAPES.DAT header: count, then per set: offset(u32) frames(u8) wcells(u8) hcells(u8)
    height(u8). Pixel value 31 is transparent."""
    index = bytearray()
    data = bytearray()
    sets = gd.CFILES
    header_size = 2 + len(sets) * 8
    for name, wwords, height, count, numblocks, _seq, block in sets:
        width = wwords * 16
        plane_bytes = wwords * 2 * height
        need = count * 5 * plane_bytes
        raw = disk.blocks(block, numblocks)
        if need > len(raw):
            # the original loads only numblocks; the last frame then runs into whatever
            # follows in memory. Read the rest from the disk instead.
            print(f"  note: {name} needs {need} bytes, original loads {len(raw)}")
            raw = disk.blocks(block, (need + 511) // 512)
        wc = width // 16
        hc = (height + 15) // 16
        offset = header_size + len(data)
        index += struct.pack("<IBBBB", offset, count, wc, hc, height)
        per_row = 16
        sheet_rows = (count + per_row - 1) // per_row
        sheet = [bytearray([31]) * ((width + 1) * per_row) for _ in range((height + 1) * sheet_rows)]
        for f in range(count):
            frame = raw[f * 5 * plane_bytes:(f + 1) * 5 * plane_bytes]
            rows = planar_image(frame, width, height, 5, plane_bytes)
            rows += [bytearray([31]) * width] * (hc * 16 - height)
            for cy in range(hc):
                for cx in range(wc):
                    for y in range(16):
                        data += rows[cy * 16 + y][cx * 16:cx * 16 + 16]
            ox = (f % per_row) * (width + 1)
            oy = (f // per_row) * (height + 1)
            for y in range(height):
                sheet[oy + y][ox:ox + width] = rows[y]
        pal = PAGE_PAL[:31] + [MAGENTA]
        out.png(f"shapes_{name}.png", scale(sheet, 3), pal)
    out.file("SHAPES.DAT", struct.pack("<H", len(sets)) + index + data)
    out.define("SHAPE_SETS", len(sets))
    out.define("SHAPE_TRANSPARENT", 31)


# --------------------------------------------------------------------------- samples, music

def convert_samples(disk, out):
    raw = disk.blocks(gd.SAMPLE_BLOCK, gd.SAMPLE_BLOCKS)
    pos = 0
    data = bytearray()
    sizes = []
    for _ in range(6):
        n = struct.unpack(">I", raw[pos:pos + 4])[0]
        pos += 4
        pcm = bytes(((b + 128) & 0xFF) for b in raw[pos:pos + n])   # signed -> unsigned
        pos += n
        sizes.append(n)
        data += struct.pack("<H", n) + pcm
    assert pos <= len(raw)
    out.file("SAMPLES.DAT", data)
    print("  sample sizes:", sizes)


def convert_music(game, out):
    with open(os.path.join(game, "songs"), "rb") as f:
        songs = f.read()
    tracks = []
    pos = 0
    load = 0
    for _ in range(28):
        n = struct.unpack(">I", songs[pos:pos + 4])[0] * 2
        pos += 4
        if load + n > 5900:
            break
        tracks.append(songs[pos:pos + n])
        pos += n
        load += n
    assert len(tracks) == 28, len(tracks)
    with open(os.path.join(game, "v6"), "rb") as f:
        v6 = f.read()
    assert len(v6) == 4628, len(v6)
    waves = v6[0:1024]
    envelopes = v6[2048:2048 + 2560]   # Seek(file,1024,OFFSET_CURRENT) in fmain.c:933

    # AY tone periods for the 84 note indices
    periods = []
    for period, offset in gd.PTABLE:
        length = (32 - offset) * 2
        freq = gd.PAL_CLOCK / (period * length)
        periods.append(min(4095, round(gd.AY_CLOCK / (16 * freq))))

    # layout: 28 x u16 track offsets, 84 x u16 AY periods, 64 x u16 notevals,
    # waves (1024), envelopes (2560), track data
    head = 28 * 2 + 84 * 2 + 64 * 2 + 1024 + 2560
    offs = []
    body = bytearray()
    for t in tracks:
        offs.append(head + len(body))
        body += t
    data = (b"".join(struct.pack("<H", o) for o in offs)
            + b"".join(struct.pack("<H", p) for p in periods)
            + b"".join(struct.pack("<H", v) for v in gd.NOTEVALS)
            + waves + envelopes + body)
    out.file("MUSIC.DAT", data)
    out.define("MUSIC_TRACKS", 28)
    out.define("MUSIC_OFF_PERIODS", 56)
    out.define("MUSIC_OFF_NOTEVALS", 56 + 168)
    out.define("MUSIC_OFF_WAVES", 56 + 168 + 128)
    out.define("MUSIC_OFF_ENVELOPES", 56 + 168 + 128 + 1024)
    out.define("MUSIC_SIZE", len(data))
    print("  track lengths:", [len(t) // 2 for t in tracks])


# --------------------------------------------------------------------------- font

def convert_font(game, out):
    with open(os.path.join(game, "fonts", "Amber", "9"), "rb") as f:
        hunk = first_hunk(f.read())
    # code: moveq #0,d0 / rts, then struct DiskFontHeader (Node 14, FileID 2, Revision 2,
    # Segment 4, Name 32) followed by struct TextFont
    tf = 4 + 14 + 2 + 2 + 4 + 32
    assert struct.unpack(">H", hunk[4 + 14:4 + 16])[0] == 0x0F80, "DiskFontHeader id"
    p = tf + 20                                   # skip tf_Message
    ysize, style, flags, xsize, baseline, smear, _acc, lo, hi = struct.unpack(
        ">HBBHHHHBB", hunk[p:p + 14])
    chardata, modulo, charloc, charspace, charkern = struct.unpack(">IHIII", hunk[p + 14:p + 32])
    n = hi - lo + 2                               # + the "not defined" glyph
    loc = [struct.unpack(">HH", hunk[charloc + i * 4:charloc + i * 4 + 4]) for i in range(n)]
    space = [struct.unpack(">h", hunk[charspace + i * 2:charspace + i * 2 + 2])[0] for i in range(n)] \
        if charspace else [xsize] * n
    kern = [struct.unpack(">h", hunk[charkern + i * 2:charkern + i * 2 + 2])[0] for i in range(n)] \
        if charkern else [0] * n
    bitmap = hunk[chardata:chardata + modulo * ysize]

    # FONT.DAT: ysize, baseline, lo, hi, modulo(u16), then n x (bitoffset u16, width u8,
    # space i8, kern i8), then bitmap (ysize rows of modulo bytes, MSB = leftmost pixel)
    data = struct.pack("<BBBBH", ysize, baseline, lo, hi, modulo)
    for (off, width), sp, kn in zip(loc, space, kern):
        data += struct.pack("<HBbb", off, width, sp, kn)
    data += bitmap
    out.file("FONT.DAT", data)
    print(f"  font: {ysize}px, chars {lo:#x}-{hi:#x}, flags {flags:#x}, modulo {modulo}")

    # preview: sample text rendered like Text() with proportional spacing
    text = "% was getting rather hungry. The Faery Tale Adventure 0123456789!?"
    rows = [bytearray(len(text) * 32 + 8) for _ in range(ysize + 2)]
    x = 2
    for ch in text:
        i = ord(ch) - lo if lo <= ord(ch) <= hi else n - 1
        off, width = loc[i]
        gx = x + kern[i]
        for y in range(ysize):
            for b in range(width):
                bit = off + b
                if bitmap[y * modulo + (bit >> 3)] & (0x80 >> (bit & 7)):
                    rows[y + 1][gx + b] = 1
        x += space[i]
    out.png("font.png", scale([r[:x + 2] for r in rows], 3), [(40, 30, 20), (255, 230, 180)])


# --------------------------------------------------------------------------- pictures

def convert_fullscreen(game, name, out, colors=None):
    img = read_ilbm(os.path.join(game, name))
    l2 = layer2_320_column_major(img.pixels, yoff=(256 - img.height) // 2)
    base = name.upper()
    if colors is None:
        colors = [((r >> 4) << 8) | ((g >> 4) << 4) | (b >> 4) for r, g, b in img.cmap[:32]]
    out.file(base + ".L2", l2)
    out.file(base + ".PAL", rgb4_palette_bytes(colors))
    out.png(name + ".png", img.pixels, [rgb4_to_rgb8(c) for c in colors])


def convert_brush(game, name, out):
    """Intro page brushes: header width(u16) height(u16), then row-major 8bpp."""
    img = read_ilbm(os.path.join(game, name))
    data = struct.pack("<HH", img.width, img.height) + b"".join(bytes(r) for r in img.pixels)
    out.file(name.upper() + ".BIN", data)
    out.png(name + ".png", img.pixels, [rgb4_to_rgb8(c) for c in gd.INTROCOLORS])


def convert_hiscreen(game, out):
    """640x57x4 status panel -> 8x8 4bpp tiles (deduplicated, incl. mirrored variants)
    + 80x8 tilemap (2 bytes per entry: tile index low, attribute) for the 80-column tilemap."""
    img = read_ilbm(os.path.join(game, "hiscreen"))
    rows = img.pixels + [bytearray(img.width)] * (64 - img.height)
    tiles = []
    lookup = {}
    tmap = bytearray()

    def pack(cell):
        return bytes((cell[i] << 4) | cell[i + 1] for i in range(0, 64, 2))

    for ty in range(8):
        for tx in range(80):
            cell = [rows[ty * 8 + y][tx * 8 + x] for y in range(8) for x in range(8)]
            variants = [
                (cell, 0),
                ([cell[y * 8 + 7 - x] for y in range(8) for x in range(8)], 0x08),          # X mirror
                ([cell[(7 - y) * 8 + x] for y in range(8) for x in range(8)], 0x04),        # Y mirror
                ([cell[(7 - y) * 8 + 7 - x] for y in range(8) for x in range(8)], 0x0C),    # both
            ]
            for v, attr in variants:
                key = pack(v)
                if key in lookup:
                    idx = lookup[key]
                    break
            else:
                idx, attr = len(tiles), 0
                key = pack(cell)
                lookup[key] = idx
                tiles.append(key)
            tmap += bytes([idx & 0xFF, attr | (idx >> 8)])
    print(f"  hiscreen: {len(tiles)} unique 8x8 tiles (budget 512)")
    assert len(tiles) <= 512
    out.file("HISCR.TIL", b"".join(tiles))
    out.file("HISCR.MAP", tmap)
    out.file("HISCR.PAL", rgb4_palette_bytes(gd.TEXTCOLORS[:16]))
    out.define("HISCR_TILES", len(tiles))

    # round trip preview
    prev = [bytearray(640) for _ in range(64)]
    for ty in range(8):
        for tx in range(80):
            idx = tmap[(ty * 80 + tx) * 2] | ((tmap[(ty * 80 + tx) * 2 + 1] & 1) << 8)
            attr = tmap[(ty * 80 + tx) * 2 + 1]
            t = tiles[idx]
            for y in range(8):
                for x in range(8):
                    sx = 7 - x if attr & 0x08 else x
                    sy = 7 - y if attr & 0x04 else y
                    b = t[sy * 4 + sx // 2]
                    prev[ty * 8 + y][tx * 8 + x] = (b >> 4) if sx % 2 == 0 else (b & 15)
    out.png("hiscreen.png", prev[:img.height], [rgb4_to_rgb8(c) for c in gd.TEXTCOLORS[:16]])
    assert prev[:img.height] == [bytearray(r) for r in img.pixels], "hiscreen round trip"


# --------------------------------------------------------------------------- main

def main():
    game, sdroot, prevdir, gendir = sys.argv[1:5]
    out = Out(sdroot, prevdir, gendir)
    disk = Disk(os.path.join(game, "image"))

    print("tiles")
    banks = convert_tiles(disk, out)
    print("world")
    sectors, maps, terra = convert_world(disk, out)
    world_previews(banks, sectors, maps, terra, out)
    area_previews(banks, sectors, maps, out)
    print("shapes")
    convert_shapes(disk, out)
    print("sound")
    convert_samples(disk, out)
    convert_music(game, out)
    print("font")
    convert_font(game, out)
    print("pictures")
    convert_fullscreen(game, "page0", out)
    convert_fullscreen(game, "winpic", out)
    for name in ("p1a", "p1b", "p2a", "p2b", "p3a", "p3b"):
        convert_brush(game, name, out)
    convert_hiscreen(game, out)
    out.write_header()


if __name__ == "__main__":
    main()
