#!/usr/bin/env python3
"""Translate the data parts of narr.asm (68000 assembler) into C.

All dc.b / dc.w data goes into one byte array narr_data[]; every label becomes
a NARR_<label> offset. Offset tables (dc.l a-b) become uint16_t arrays of
absolute offsets. Code (_question, _placard_text) is skipped; it is re-implemented in C.

Usage: narr2c.py <narr.asm> <out-dir>
"""
import os
import re
import sys

SKIP_OPS = {"public", "cseg", "dseg", "move.l", "add.w", "add.l", "lea", "jmp", "end"}


def split_operands(s):
    """Split an operand list at commas outside of quotes; strip trailing comments."""
    ops, cur, quote = [], "", None
    for ch in s:
        if quote:
            cur += ch
            if ch == quote:
                quote = None
        elif ch in "'\"":
            quote = ch
            cur += ch
        elif ch == ",":
            ops.append(cur.strip())
            cur = ""
        elif ch == ";":
            break
        else:
            cur += ch
    if cur.strip():
        ops.append(cur.strip())
    return ops


def parse(path):
    data = bytearray()
    labels = {}
    equs = {}
    tables = {}     # label -> list of (a, b) for dc.l a-b
    order = []
    current_table = None
    with open(path, encoding="latin-1") as f:
        for raw in f:
            line = raw.rstrip("\n")
            if not line.strip() or line.lstrip().startswith(";"):
                continue
            m = re.match(r"^([A-Za-z_][\w]*)?\s*(.*)$", line)
            label, rest = m.group(1), m.group(2).strip()
            if label and not line[0].isspace():
                parts = rest.split(None, 1)
                if parts and parts[0].lower() == "equ":
                    equs[label] = int(split_operands(parts[1])[0])
                    continue
                labels[label] = len(data)
                order.append(label)
                current_table = label
            if not rest or rest.startswith(";"):
                continue
            parts = rest.split(None, 1)
            op = parts[0].lower()
            args = parts[1] if len(parts) > 1 else ""
            if op in SKIP_OPS:
                continue
            if op == "dc.b":
                for operand in split_operands(args):
                    if operand[0] in "'\"":
                        data += operand[1:-1].encode("latin-1")
                    else:
                        data.append(eval_expr(operand, equs) & 0xFF)
            elif op == "dc.w":
                for operand in split_operands(args):
                    v = eval_expr(operand, equs) & 0xFFFF
                    data += bytes([v & 0xFF, v >> 8])
            elif op == "dc.l":
                for operand in split_operands(args):
                    a, b = operand.split("-")
                    tables.setdefault(current_table, []).append(a.strip())
            else:
                raise ValueError(f"unhandled line: {line}")
    return data, labels, tables, order


def eval_expr(expr, equs):
    expr = re.sub(r"[A-Za-z_]\w*", lambda m: str(equs[m.group(0)]), expr)
    expr = re.sub(r"\$([0-9A-Fa-f]+)", lambda m: str(int(m.group(1), 16)), expr)
    expr = re.sub(r"\b0+(\d)", r"\1", expr)      # decimal with leading zeros
    expr = expr.replace("/", "//")
    return int(eval(expr, {"__builtins__": {}}))


def cname(label):
    return label.lstrip("_")


def write_c(data, labels, tables, order, outdir):
    os.makedirs(outdir, exist_ok=True)
    with open(os.path.join(outdir, "narr.h"), "w") as h:
        h.write("/* generated by tools/narr2c.py from narr.asm - do not edit */\n")
        h.write("#ifndef NARR_H\n#define NARR_H\n\n#include <stdint.h>\n\n")
        h.write(f"#define NARR_SIZE {len(data)}\n")
        h.write("#define NARR_XY 128\n#define NARR_ETX 0\n\n")
        for label in order:
            if label not in tables:
                h.write(f"#define NARR_{cname(label)} {labels[label]}\n")
        h.write("\nextern const uint8_t narr_data[NARR_SIZE];\n")
        for label, entries in tables.items():
            h.write(f"extern const uint16_t narr_{cname(label)}[{len(entries)}];\n")
        h.write("\n#endif\n")
    with open(os.path.join(outdir, "narr.c"), "w") as c:
        c.write("/* generated by tools/narr2c.py from narr.asm - do not edit */\n")
        c.write('#include "narr.h"\n\n')
        for label, entries in tables.items():
            vals = ", ".join(str(labels[e]) for e in entries)
            c.write(f"const uint16_t narr_{cname(label)}[{len(entries)}] = {{ {vals} }};\n")
        c.write("\nconst uint8_t narr_data[NARR_SIZE] = {\n")
        for i in range(0, len(data), 16):
            c.write("    " + ", ".join(str(b) for b in data[i:i + 16]) + ",\n")
        c.write("};\n")


def main():
    data, labels, tables, order = parse(sys.argv[1])
    write_c(data, labels, tables, order, sys.argv[2])
    print(f"narr: {len(data)} bytes, {len(labels)} labels, tables: "
          + ", ".join(f"{k}[{len(v)}]" for k, v in tables.items()))


if __name__ == "__main__":
    main()
